"""About Project page: purpose, how it works, technology, data integrity and limitations."""
from __future__ import annotations

import streamlit as st

from .. import config, interpret, ui


def render(df, fdf, active):
    ui.page_header("About Project", "Crop Yield Explorer",
                   "An academic data exploration project for NS-CSC 229 Integrated Design Project II, developed by Group 65.")
    c1, c2, c3 = st.columns(3, gap="medium")
    ui.fact(c1, "What it is", "A Streamlit application for exploring crop and yield records: filtering, summary statistics, charts and correlations.")
    ui.fact(c2, "What it is not", "It is not a crop prediction system. It describes the records that are loaded and gives no forecasts or farm advice.")
    ui.fact(c3, "Who it is for", "Students, instructors and beginners who want a careful first look at a small crop dataset.")

    ui.section("How it works")
    a, b, c = st.columns(3, gap="medium")
    ui.fact(a, "1. Load", "A bundled synthetic sample or an uploaded CSV file is validated: structure, types, plausible ranges, duplicates and missing values.")
    ui.fact(b, "2. Filter", "Crop, region, season, year, rainfall, temperature, fertilizer and land-area filters update every page together.")
    ui.fact(c, "3. Explore", "Overview, crop analysis and relationships pages present statistics and interactive charts with plain-language interpretation.")

    ui.section("Technology")
    ui.chips(["Python", "Streamlit", "pandas", "NumPy", "Plotly", "Matplotlib", "Seaborn", "pytest"])

    ui.section("Data and integrity")
    ui.note("The bundled sample is <b>synthetic</b>. It was generated by <code>scripts/generate_sample_data.py</code> with a fixed random seed "
            "(720 records, 2015 to 2024, eight crops, six regions) and some values were deliberately removed to demonstrate missing-value "
            "handling. It must not be cited as real agricultural data.", "caution")

    ui.section("Correlation is not causation")
    for p in interpret.CAUSATION_POINTS:
        st.markdown(f"- {p}")

    ui.section("Limitations")
    st.markdown(
        "- Results describe only the records loaded; they are not forecasts or recommendations for any farm.\n"
        "- Correlations use pairwise complete observations; missing values are not imputed.\n"
        "- Narrow filters leave few records, which makes statistics unstable.\n"
        "- Uploaded files must use recognised column names (see Dataset Manager).\n"
        "- Data are held in the browser session only and are not stored by the application."
    )
