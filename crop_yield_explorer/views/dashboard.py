"""Dashboard page: KPIs, summary statistics and headline charts."""
from __future__ import annotations

import streamlit as st

from .. import charts, config, interpret, stats, ui


def render(df, fdf, active, synthetic, source):
    ui.header(config.APP_TITLE, config.APP_TAGLINE, synthetic)
    if synthetic:
        ui.note("The sample dataset is <b>synthetic</b>: it was generated by a seeded program for demonstration. "
                "It does not contain verified real-world agricultural observations and must not be cited as research findings.",
                "caution")
    st.caption(f"Data source: {source}" + (f"  |  Active filters: {'; '.join(active)}" if active else "  |  No filters applied"))
    if not ui.require_records(fdf):
        return
    k = stats.kpis(fdf)
    cols = st.columns(5)
    ui.kpi(cols[0], "Crop records", f"{k['records']:,}", f"of {len(df):,} loaded")
    ui.kpi(cols[1], "Total production", ui.fmt_num(k["total_production"], 1, "t") if k["total_production"] is not None else "n/a", "tonnes")
    ui.kpi(cols[2], "Average yield", ui.fmt_num(k["mean_yield"], 2), "t/ha")
    ui.kpi(cols[3], "Highest yield", ui.fmt_num(k["max_yield"], 2), f"t/ha, {k['max_yield_crop']}")
    ui.kpi(cols[4], "Crop types", f"{k['crops']:,}", "distinct crops")

    st.markdown("## Summary statistics")
    d = stats.describe_numeric(fdf)
    st.dataframe(d.style.format({c: "{:,.2f}" for c in ["Mean", "Median", "Minimum", "Maximum", "Std. deviation"]}, na_rep="n/a"),
                 hide_index=True, width="stretch")

    st.markdown("## Headline charts")
    cmap = charts.color_map(df["crop"])
    c1, c2 = st.columns(2)
    with c1:
        st.plotly_chart(charts.yield_by_crop(fdf), width="stretch", key="d_yc")
        ui.interp(interpret.yield_by_crop(fdf))
    with c2:
        if "production_tonnes" in fdf.columns and fdf["production_tonnes"].notna().any():
            st.plotly_chart(charts.production_by_crop(fdf, cmap), width="stretch", key="d_pc")
            ui.interp(interpret.production(fdf))
        else:
            st.info("The loaded data has no production column.")
    if "region" in fdf.columns and fdf["region"].notna().any():
        st.plotly_chart(charts.region_yield(fdf), width="stretch", key="d_ry")
        ui.interp(interpret.region(fdf))
    ui.note("Charts on this page describe the data. Where relationships are discussed on other pages, they are "
            "<b>correlations</b>, which do not establish causation.")
