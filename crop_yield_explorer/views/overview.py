"""Overview page: headline figures and the main analytical views."""
from __future__ import annotations

import streamlit as st

from .. import charts, config, interpret, stats, ui


def render(df, fdf, active):
    ui.page_header("Overview", "Crop production at a glance", config.APP_TAGLINE)
    if st.session_state.get("synthetic"):
        ui.note("The sample dataset is <b>synthetic</b>: it was generated by a seeded program for demonstration and does not "
                "contain real agricultural observations. Do not cite it as research findings.", "caution")
    ui.active_filters_chips(active)
    if not ui.require_records(fdf):
        return
    k = stats.kpis(fdf)
    where = f"{k['max_yield_crop']}" + (f", {k['max_yield_region']}" if k.get("max_yield_region") else "")
    ui.kpi_grid([
        ("records", "Crop records", f"{k['records']:,}", "", f"of {len(df):,} loaded records"),
        ("production", "Total production", ui.fmt_num(k["total_production"], 1) if k["total_production"] is not None else "n/a", "t", "tonnes in the selection"),
        ("yield", "Average yield", ui.fmt_num(k["mean_yield"], 2), "t/ha", "mean of all selected records"),
        ("peak", "Highest yield", ui.fmt_num(k["max_yield"], 2), "t/ha", where),
        ("crops", "Crop types", f"{k['crops']:,}", "", "distinct crops in the selection"),
    ])

    cmap = charts.color_map(df["crop"])
    ui.section("Production and trend", "How much was produced, and how the average yield moved over time.")
    c1, c2 = st.columns([3, 2], gap="medium")
    with c1, ui.card():
        fig = charts.yield_trend(fdf)
        if fig is not None:
            ui.plot(fig, "o_trend")
            ui.interp(interpret.trend(fdf))
        else:
            ui.empty_state("Trend not available", "At least two different years are needed to draw a trend.")
    with c2, ui.card():
        if "production_tonnes" in fdf.columns and fdf["production_tonnes"].notna().any():
            ui.plot(charts.production_by_crop(fdf, cmap), "o_prod")
            ui.interp(interpret.production(fdf))
        else:
            ui.empty_state("No production data", "The loaded data has no production column.")

    ui.section("Crop performance", "Compare crop types and see how individual yields are spread.")
    c3, c4 = st.columns(2, gap="medium")
    with c3, ui.card():
        ui.plot(charts.yield_by_crop(fdf), "o_yc")
        ui.interp(interpret.yield_by_crop(fdf))
    with c4, ui.card():
        ui.plot(charts.yield_distribution(fdf, cmap, False), "o_dist")
        ui.interp(interpret.distribution(fdf))

    if "region" in fdf.columns and fdf["region"].notna().any():
        ui.section("Regional comparison", "Mean yield by region, and by region and crop together.")
        c5, c6 = st.columns(2, gap="medium")
        with c5, ui.card():
            ui.plot(charts.region_yield(fdf), "o_reg")
            ui.interp(interpret.region(fdf))
        with c6, ui.card():
            if fdf["crop"].nunique() > 1 and fdf["region"].nunique() > 1:
                ui.plot(charts.region_crop_heatmap(fdf), "o_rch")
                ui.interp("Darker cells indicate higher mean yield. Empty cells mean no records for that crop in that region.")
            else:
                ui.empty_state("Heatmap needs more variety", "Select at least two crops and two regions to compare them.")
    ui.note("The charts describe the loaded records. Where relationships are discussed on the <b>Relationships</b> page they are "
            "<b>correlations</b>, which do not establish cause and effect.")
